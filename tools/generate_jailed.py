#!/usr/bin/env python3
"""Adapt the saved Jail-ed 1.1b decompilation to native pointer widths.

This is the editor shipped in Cell Block A 1.3b. Core behavior remains recovered
C; file dialogs, safe map I/O and the SDL event loop live in jailed.cpp.
"""
from pathlib import Path
import re
from extract_original import address_bytes
ROOT = Path(__file__).resolve().parents[1]
b = (ROOT / 'analysis/JAILED.coff').read_bytes()
assert address_bytes(b, 0x2368, 5) == b'1.1b\0'
names = ('reset_map', 'draw_map', 'draw_tile', 'screen_click', 'mappic')
texts = []
for name in names:
    s = (ROOT / 'analysis/jailed-1.3b' / ('_' + name + '.c')).read_text()
    s = s.replace('(int)&', '(uintptr_t)&')
    for n in names:
        s = re.sub(r'\b_' + n + r'\b', 'jailed_' + n, s)
    for old, new in [('_CUR_EDIT', 'jailed_tool'), ('_mouse_x', 'jailed_mouse_x'),
                     ('_mouse_y', 'jailed_mouse_y'), ('_mouse_b', 'jailed_mouse_b')]:
        s = s.replace(old, new)
    if name == 'screen_click':
        s = s.replace('{', '{\n  /* Native windows can report coordinates outside the canvas. */\n'
                      '  if (jailed_mouse_x < 0 || jailed_mouse_x >= 640 ||\n'
                      '      jailed_mouse_y < 0 || jailed_mouse_y >= 416) return;\n', 1)
    texts.append(s)
(ROOT / 'src/jailed_recovered.c').write_text(
    '/* Generated by tools/generate_jailed.py from the 1.3b distribution. */\n'
    '#include "jailed.h"\nint jailed_tool=1, jailed_mouse_x, jailed_mouse_y, jailed_mouse_b;\n'
    + '\n'.join(texts))
